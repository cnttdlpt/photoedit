    func testSpatialRoundingMatchesAndroid() throws {
        var pixels = Array(repeating: UInt8(0), count: 3 * 3 * 4)
        for index in stride(from: 3, to: pixels.count, by: 4) { pixels[index] = 255 }
        pixels.replaceSubrange(16..<20, with: [225, 225, 225, 128])
        let source = try RasterImage(width: 3, height: 3, pixels: pixels)
        var settings = Settings(); settings.sharpness = -3
        // Java: 225 + (225 - 0) * -3 * 0.18 = 103.5, rounded to 104.
        let result = try ColorEngine.render(source, settings: settings)
        XCTAssertEqual(Array(result.pixels[16..<20]), [104, 104, 104, 128])
    }

    func testParallelPixelBatchesMatchAndroidAcrossRowBoundaries() throws {
