    func testIdentityLUTAndDomainClamping() throws {
        let lut = try CubeLut.parse(identity)
        let sample = lut.sample(0.25, 0.67, 0.9)
        XCTAssertEqual(sample.red, 0.25, accuracy: 0.000001)
        XCTAssertEqual(sample.green, 0.67, accuracy: 0.000001)
        XCTAssertEqual(sample.blue, 0.9, accuracy: 0.000001)
        let clamped = lut.sample(-10, 3, 0)
        XCTAssertEqual(clamped.red, 0); XCTAssertEqual(clamped.green, 1); XCTAssertEqual(clamped.blue, 0)
    }

