    /// Expected FNV-1a hashes come from AndroidParityFixture.java running the original Java classes.
    /// One 13×11 image exercises alpha, clipped channels, borders, and clarity's broad neighborhood.
    func testAndroidPixelParity() throws {
        let source = try fixtureImage()
        func check(_ settings: Settings, _ expected: String, lut: CubeLut? = nil, file: StaticString = #filePath, line: UInt = #line) throws {
            let rendered = try ColorEngine.render(source, settings: settings, lut: lut)
            var hash: UInt64 = 0xcbf29ce484222325
            for byte in rendered.pixels { hash = (hash ^ UInt64(byte)) &* 0x100000001b3 }
            XCTAssertEqual(String(format: "%016llx", hash), expected, file: file, line: line)
        }
        var s = Settings(); try check(s, "22180939cf4cfbdb")
        s.exposure = 1; try check(s, "9ca0f4b73b8ed5b7")
        s = Settings(); s.red = 7; s.blue = -6; s.temperature = 37; try check(s, "252e5d23359850ac")
        s = Settings(); s.highlight = -2; s.shadow = 3; s.color = 4; s.dr = 400
        s.colorChrome = 2; s.chromeBlue = 1; try check(s, "64ef2e3a327f0b15")
        s = Settings(); s.grain = 18; s.grainSize = 2; try check(s, "4bde4cff5fc4fa9b")
        s = Settings(); s.nr = 4; try check(s, "f237ebc4ed31cce4")
        s = Settings(); s.sharpness = 3; s.clarity = -5; try check(s, "77db1c6007af0caf")
        s = Settings(); s.exposure = -0.7; s.highlight = 2; s.shadow = -1; s.color = -3
        s.red = 3; s.blue = -2; s.temperature = -15; s.sharpness = 2; s.nr = -1
        s.grain = 8; s.grainSize = 1; s.clarity = 3; s.colorChrome = 1; s.chromeBlue = 2; s.lutAmount = 63; s.dr = 200
        let lut = try CubeLut.parse("TITLE \"Domain swap\"\nDOMAIN_MIN -0.1 0.1 0.05\nDOMAIN_MAX 1.2 0.9 1.05\nLUT_3D_SIZE 2\n0.05 0.1 0\n0.05 0.3 1\n0.05 0.9 0\n0.05 1.1 1\n0.95 0.1 0\n0.95 0.3 1\n0.95 0.9 0\n0.95 1.1 1\n")
        try check(s, "4d255e8c74abd734", lut: lut)
    }

    private func fixtureImage(width: Int = 13, height: Int = 11) throws -> RasterImage {
        var pixels: [UInt8] = []
        for y in 0..<height { for x in 0..<width {
            pixels.append(UInt8((x * 31 + y * 17 + 11) & 255))
            pixels.append(UInt8((x * 7 + y * 41 + 29) & 255))
            pixels.append(UInt8((x * 53 + y * 3 + 73) & 255))
            pixels.append(UInt8((x * 19 + y * 23 + 97) & 255))
        } }
        return try RasterImage(width: width, height: height, pixels: pixels)
    }
